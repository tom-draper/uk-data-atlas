import { readdir, readFile, writeFile } from "fs/promises";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATASETS_DIR = join(ROOT, "lib", "datasets");
const OUTPUT = join(DATASETS_DIR, "generated.ts");
const CHART_OUTPUT = join(DATASETS_DIR, "generatedCharts.tsx");

async function main() {
	const files = (await readdir(DATASETS_DIR))
		.filter((file) => file.endsWith(".ts") && !["index.ts", "types.ts", "generated.ts"].includes(file))
		.sort();
	const definitions = await Promise.all(files.map(async (file) => {
		const source = await readFile(join(DATASETS_DIR, file), "utf8");
		const name = /export const (\w+Definition)\b/.exec(source)?.[1];
		const type = /type:\s*"([^"]+)"/.exec(source)?.[1];
		const datasetType = /ScalarDatasetDefinition<(\w+)>/.exec(source)?.[1];
		const componentPath = /componentPath:\s*"([^"]+)"/.exec(source)?.[1];
		if (!name) throw new Error(`${file} must export a named *Definition constant.`);
		if (!type) throw new Error(`${file} must declare a string literal dataset type.`);
		if (!datasetType) throw new Error(`${file} must use ScalarDatasetDefinition with its dataset type.`);
		const datasetImport = new RegExp(`import type \\{ ${datasetType} \\} from "([^"]+)";`).exec(source)?.[1];
		if (!datasetImport) throw new Error(`${file} must import ${datasetType} as a type.`);
		if (!componentPath) throw new Error(`${file} must declare a chart component path.`);
		return { file: file.replace(/\.ts$/, ""), name, type, datasetType, datasetImport, componentPath };
	}));
	const imports = definitions.map(({ file, name }) => `import { ${name} } from "./${file}";`).join("\n");
	const datasetTypeImports = definitions.map(({ datasetType, datasetImport }) => `import type { ${datasetType} } from "${datasetImport}";`).join("\n");
	const values = definitions.map(({ name }) => `\t${name},`).join("\n");
	const types = definitions.map(({ type }) => `"${type}"`).join(" | ");
	const datasetTypes = definitions.map(({ datasetType }) => datasetType).join(" | ");
	const records = definitions.map(({ type, datasetType }) => `\t${type}: Record<string, ${datasetType}>;`).join("\n");
	await writeFile(OUTPUT, `// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { ScalarDatasetDefinition } from "./types";\n${datasetTypeImports}\n${imports}\n\nexport type ScalarDatasetType = ${types};\nexport type ScalarDataset = ${datasetTypes};\nexport type ScalarDatasetRecords = {\n${records}\n};\n\nexport const SCALAR_DATASET_DEFINITIONS: readonly ScalarDatasetDefinition<ScalarDataset>[] = [\n${values}\n];\n`);
	const chartImports = definitions.map(({ type, componentPath }) => `import ${type[0].toUpperCase()}${type.slice(1)}Chart from "${componentPath}";`).join("\n");
	const chartValues = definitions.map(({ type }) => `\t${type}: ${type[0].toUpperCase()}${type.slice(1)}Chart,`).join("\n");
	await writeFile(CHART_OUTPUT, `"use client";\n// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { ComponentType } from "react";\nimport type { ScalarDatasetType } from "./generated";\n${chartImports}\n\nexport const SCALAR_CHART_COMPONENTS: Record<ScalarDatasetType, ComponentType<any>> = {\n${chartValues}\n};\n`);
}

main();
