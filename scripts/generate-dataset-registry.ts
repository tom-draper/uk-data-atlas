import { readdir } from "fs/promises";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import {
	loadModule,
	readCatalogueDefinitions,
	writeGenerated,
} from "../pipeline/src/build-catalogue-registry";
import {
	chartDefinitionFiles,
	chartMetadata,
} from "./dataset-registry-metadata";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATASETS_DIR = join(ROOT, "lib", "datasets");
const OUTPUT = join(DATASETS_DIR, "generated.ts");
const CHART_OUTPUT = join(DATASETS_DIR, "generatedCharts.tsx");

async function main() {
	const catalogueDefinitions = await readCatalogueDefinitions();
	const files = chartDefinitionFiles(await readdir(DATASETS_DIR));
	const definitions = await Promise.all(
		files.map(async (file) => {
			const definition = chartMetadata(
				file,
				await loadModule(DATASETS_DIR, file),
			);
			const catalogue = catalogueDefinitions.find(
				(candidate) => candidate.type === definition.type,
			);
			if (!catalogue)
				throw new Error(
					`${file} has no registered catalogue definition for ${definition.type}.`,
				);
			return {
				file: file.replace(/\.ts$/, ""),
				...definition,
				chartPending: catalogue.chartPending,
			};
		}),
	);
	const chartDefinitions = definitions.filter(
		(definition) => !definition.chartPending,
	);
	const imports = chartDefinitions
		.map(({ file, name }) => `import { ${name} } from "./${file}";`)
		.join("\n");
	const values = chartDefinitions.map(({ name }) => `\t${name},`).join("\n");
	await writeGenerated(
		OUTPUT,
		`// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { CatalogueDataset, CatalogueDatasetRecords, CatalogueDatasetType } from "../data/catalog/generated";\nimport type { ChartDatasetDefinition } from "./types";\n${imports}\n\nexport type ChartDatasetType = CatalogueDatasetType;\nexport type ChartDataset = CatalogueDataset;\nexport type ChartDatasetRecords = CatalogueDatasetRecords;\n\nexport const CHART_DATASET_DEFINITIONS: readonly ChartDatasetDefinition<ChartDataset>[] = [\n${values}\n];\n`,
	);
	const charts = chartDefinitions.flatMap(({ charts }) => charts);
	const componentPaths = [
		...new Set(charts.map((chart) => chart.componentPath)),
	];
	const componentNameForPath = new Map(
		componentPaths.map((path, index) => [path, `Chart${index}`]),
	);
	const chartImports = componentPaths
		.map((path, index) => `import Chart${index} from "${path}";`)
		.join("\n");
	const chartPresentations = componentPaths
		.map(
			(_path, index) =>
				`const Chart${index}Presentation = {\n\tcomponent: (props) => (\n\t\t<Chart${index}\n\t\t\t{...(props as ComponentProps<typeof Chart${index}>)}\n\t\t/>\n\t),\n} satisfies ChartPresentation;`,
		)
		.join("\n\n");
	const chartValues = charts
		.map((chart) => {
			const componentName = componentNameForPath.get(chart.componentPath);
			if (!componentName)
				throw new Error(`No component registered for ${chart.key}.`);
			return `\t"${chart.key}": ${componentName}Presentation,`;
		})
		.join("\n");
	await writeGenerated(
		CHART_OUTPUT,
		`"use client";\n// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { ComponentProps } from "react";\nimport type { ChartPresentation, ChartPresentationRegistry } from "./types";\n${chartImports}\n\n${chartPresentations}\n\nexport const CHART_PRESENTATIONS = {\n${chartValues}\n} satisfies ChartPresentationRegistry;\n\nexport type ChartPresentationKey = keyof typeof CHART_PRESENTATIONS;\n\nexport const getChartPresentation = (\n\tkey: string,\n): ChartPresentation | undefined => CHART_PRESENTATIONS[key as ChartPresentationKey];\n`,
	);
}

main();
