import { readdir, readFile, writeFile } from "fs/promises";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DATASETS_DIR = join(ROOT, "lib", "datasets");
const CATALOGUE_DEFINITIONS_DIR = join(ROOT, "lib", "data", "catalog", "definitions");
const CATALOGUE_REGISTRY = join(ROOT, "lib", "data", "catalog", "registry.ts");
const CATALOGUE_TYPES = join(ROOT, "lib", "data", "catalog", "generated.ts");
const OUTPUT = join(DATASETS_DIR, "generated.ts");
const CHART_OUTPUT = join(DATASETS_DIR, "generatedCharts.tsx");

async function main() {
	const catalogueDefinitions = await Promise.all((await readdir(CATALOGUE_DEFINITIONS_DIR))
		.filter((file) => file.endsWith(".ts") && file !== "index.ts")
		.sort()
		.map(async (file) => {
			const source = await readFile(join(CATALOGUE_DEFINITIONS_DIR, file), "utf8");
			const name = /export const (\w+DatasetDefinition)\b/.exec(source)?.[1];
			const type = /type:\s*"([^"]+)"/.exec(source)?.[1];
			const datasetType = /DatasetDefinition<(\w+)>/.exec(source)?.[1];
			if (!name) throw new Error(`${file} must export a named *DatasetDefinition constant.`);
			if (!type) throw new Error(`${file} must declare a string literal dataset type.`);
			if (!datasetType) throw new Error(`${file} must use DatasetDefinition with its dataset type.`);
			const datasetImport = new RegExp(`import type \\{ ${datasetType} \\} from "([^"]+)";`).exec(source)?.[1];
			if (!datasetImport) throw new Error(`${file} must import ${datasetType} as a type.`);
			return { file: file.replace(/\.ts$/, ""), name, type, datasetType, datasetImport };
		}));
	const catalogueByName = new Map(catalogueDefinitions.map((definition) => [definition.name, definition]));
	const files = (await readdir(DATASETS_DIR))
		.filter((file) => file.endsWith(".ts") && !["index.ts", "types.ts", "ingestion.ts", "generated.ts"].includes(file))
		.sort();
	const definitions = await Promise.all(files.map(async (file) => {
		const source = await readFile(join(DATASETS_DIR, file), "utf8");
		const name = /export const (\w+Definition)\b/.exec(source)?.[1];
		const catalogueDefinition = /import \{ (\w+DatasetDefinition) \} from "@\/lib\/data\/catalog\/definitions";/.exec(source)?.[1];
		const datasetType = /ChartDatasetDefinition<(\w+)>/.exec(source)?.[1];
		const componentPaths = [...source.matchAll(/componentPath:\s*"([^"]+)"/g)].map((match) => match[1]);
		const chartKeys = [...source.matchAll(/key:\s*"([^"]+)"/g)].map((match) => match[1]);
		if (!name) throw new Error(`${file} must export a named *Definition constant.`);
		if (!catalogueDefinition) throw new Error(`${file} must import its catalogue definition.`);
		if (!datasetType) throw new Error(`${file} must use ChartDatasetDefinition with its dataset type.`);
		const catalogue = catalogueByName.get(catalogueDefinition);
		if (!catalogue) throw new Error(`${file} imports an unregistered catalogue definition: ${catalogueDefinition}.`);
		if (datasetType !== catalogue.datasetType) throw new Error(`${file} must use ${catalogue.datasetType} for its chart definition.`);
		if (!componentPaths.length || componentPaths.length !== chartKeys.length) throw new Error(`${file} must declare matching chart keys and component paths.`);
		return { file: file.replace(/\.ts$/, ""), name, charts: chartKeys.map((key, index) => ({ key, componentPath: componentPaths[index] })) };
	}));
	const catalogueImports = catalogueDefinitions.map(({ file, name }) => `import { ${name} } from "./definitions/${file}";`).join("\n");
	const catalogueValues = catalogueDefinitions.map(({ name }) => `\t${name},`).join("\n");
	await writeFile(CATALOGUE_REGISTRY, `// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { DatasetDefinition } from "./types";\n${catalogueImports}\n\n/** The complete framework-neutral catalogue used by compilers and API consumers. */\nexport const CATALOGUE_DATASET_DEFINITIONS: readonly DatasetDefinition[] = [\n${catalogueValues}\n];\n`);
	const catalogueTypeImports = catalogueDefinitions.map(({ datasetType, datasetImport }) => `import type { ${datasetType} } from "${datasetImport}";`).join("\n");
	const catalogueTypes = catalogueDefinitions.map(({ type }) => `"${type}"`).join(" | ");
	const catalogueDatasetTypes = catalogueDefinitions.map(({ datasetType }) => datasetType).join(" | ");
	const catalogueRecords = catalogueDefinitions.map(({ type, datasetType }) => `\t${type}: Record<string, ${datasetType}>;`).join("\n");
	await writeFile(CATALOGUE_TYPES, `// Generated by scripts/generate-dataset-registry.ts. Do not edit.\n${catalogueTypeImports}\n\nexport type CatalogueDatasetType = ${catalogueTypes};\nexport type CatalogueDataset = ${catalogueDatasetTypes};\nexport type CatalogueDatasetRecords = {\n${catalogueRecords}\n};\n`);
	const imports = definitions.map(({ file, name }) => `import { ${name} } from "./${file}";`).join("\n");
	const values = definitions.map(({ name }) => `\t${name},`).join("\n");
	await writeFile(OUTPUT, `// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { CatalogueDataset, CatalogueDatasetRecords, CatalogueDatasetType } from "../data/catalog/generated";\nimport type { ChartDatasetDefinition } from "./types";\n${imports}\n\nexport type ChartDatasetType = CatalogueDatasetType;\nexport type ChartDataset = CatalogueDataset;\nexport type ChartDatasetRecords = CatalogueDatasetRecords;\n\nexport const CHART_DATASET_DEFINITIONS: readonly ChartDatasetDefinition<ChartDataset>[] = [\n${values}\n];\n`);
	const charts = definitions.flatMap(({ charts }) => charts);
	const chartImports = charts.map((chart, index) => `import Chart${index} from "${chart.componentPath}";`).join("\n");
	const chartValues = charts.map((chart, index) => `\t"${chart.key}": Chart${index},`).join("\n");
	await writeFile(CHART_OUTPUT, `"use client";\n// Generated by scripts/generate-dataset-registry.ts. Do not edit.\nimport type { ComponentType } from "react";\n${chartImports}\n\nexport const CHART_COMPONENTS: Record<string, ComponentType<any>> = {\n${chartValues}\n};\n`);
}

main();
