test("reports only files generated by successful stages, with their sizes", async (context) => {
	const directory = mkdtempSync(join(tmpdir(), "atlas-assets-"));
	context.onTestFinished(() =>
		rmSync(directory, { recursive: true, force: true }),
	);
	mkdirSync(join(directory, "data/build"), { recursive: true });
	writeFileSync(join(directory, "data/build/untouched.json"), "old");
	const stage = {
		name: "example",
		dependencies: [],
		args: [],
		writes: ["data/build"],
	};
	const lines: string[] = [];
	const cache = () =>
		createStageCache({ root: directory, codeFiles: () => [] });
	const options = {
		stages: [stage],
		createCache: cache,
		log: (line: string) => lines.push(line),
		execute: () => {
			mkdirSync(join(directory, "data/build/nested"), {
				recursive: true,
			});
			writeFileSync(
				join(directory, "data/build/nested/result.json"),
				"hello",
			);
			return 0;
		},
	};
	assert.equal(await runBuild(options), 0);
	assert.match(
		lines.join("\n"),
		/Generated assets \(1 file\):[\s\S]*data\/[\s\S]*nested\/[\s\S]*result\.json \(5 B\)/,
	);
	assert.doesNotMatch(lines.join("\n"), /untouched\.json/);
	lines.length = 0;
	assert.equal(await runBuild(options), 0);
	assert.doesNotMatch(lines.join("\n"), /Generated assets/);
});

function fixture(context: TestContext) {
	const directory = mkdtempSync(join(tmpdir(), "atlas-build-data-"));
	context.onTestFinished(() =>
		rmSync(directory, { recursive: true, force: true }),
	);
	const trace = join(directory, "trace.jsonl");
	const fixtureRunner = join(directory, "runner.mjs");
	writeFileSync(
		fixtureRunner,
		`import { appendFileSync } from "node:fs";
import { runBuild } from ${JSON.stringify(pathToFileURL(runner).href)};
try {
  process.exitCode = await runBuild({
    argv: process.argv.slice(2),
    execute(stage) {
      appendFileSync(process.env.BUILD_TRACE, JSON.stringify({ args: stage.args }) + "\\n");
      return stage.args.at(-1) === process.env.BUILD_FAIL ? 23 : 0;
    },
  });
} catch (error) { console.error("Error: " + error.message); process.exitCode = 1; }
`,
	);
	return {
		directory,
		run(argv: string[], fail = "", script = fixtureRunner) {
			return spawnSync(process.execPath, [script, ...argv], {
				cwd: directory,
				encoding: "utf8",
				env: {
					...process.env,
					BUILD_TRACE: trace,
					BUILD_FAIL: fail,
					DATA_BUILD_CACHE_DIR: join(directory, "cache"),
				},
			});
		},
		commands(): string[][] {
			try {
				return readFileSync(trace, "utf8")
					.trim()
					.split("\n")
					.map((line) => {
						const entry = JSON.parse(line);
						return entry.args;
					});
			} catch (error) {
				if (
					error instanceof Error &&
					"code" in error &&
					error.code === "ENOENT"
				)
					return [];
				throw error;
			}
		},
	};
}

function stages(result: ReturnType<ReturnType<typeof fixture>["run"]>) {
	assert.equal(result.status, 0, result.stderr);
	return result.stdout
		.trim()
		.split("\n")
		.filter((line) =>
			/^[a-z][a-z-]*: (running|would run|unchanged)/.test(line),
		)
		.map((line) => line.split(":")[0]);
}

