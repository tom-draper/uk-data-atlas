/**
 * Compile every boundary release into a map resource: its tiles and the hashes and
 * sizes of whole-release downloads generated by the API.
 *
 * A release takes from seconds to minutes, so one whose inputs have not changed
 * since it was last compiled is kept rather than rebuilt. Its inputs are the
 * geometry source file, the names the tiles carry, the release's title and
 * attribution, and the compiler's own code; `map-resources/build-state.json`
 * records the hash of all four, and the descriptor, for each release.
 */

const sourceFiles = (directory: string) =>
	readdirSync(
		resolve(
			resolve(dirname(fileURLToPath(import.meta.url)), "../../.."),
			directory,
		),
	)
		.filter((name) => name.endsWith(".ts"))
		.map((name) => `${directory}/${name}`);

/**
 * The code a map resource is compiled by, relative to the repository root: a change
 * to any of it rebuilds every release.
 */
const COMPILER_SOURCES = [
	...sourceFiles("packages/map-tiles/src/node/mapResource"),
	// The tiler, shared with the website's precompile.
	...sourceFiles("packages/map-tiles/src"),
	"packages/artifacts/src/parquet.ts",
	"pipeline/src/atlas/flatDownloads.ts",
	"pipeline/src/maps/compileMapResource.ts",
	"pipeline/src/maps/mapResourceWorker.ts",
	"pipeline/src/maps/buildMapResource.ts",
	// How areas are read, corrected and rounded, which the geometry store
	// shares: the full tier is built from the store and must match.
	"pipeline/src/maps/compileGeometryValidity.ts",
	"packages/geometry/src/areaGeometry.ts",
	"packages/geometry/src/geoJsonProperties.ts",
	"packages/geometry/src/geometrySubstitution.ts",
	"packages/geometry/src/gridOffset.ts",
	"packages/geography/src/packedGeometry.ts",
	"packages/geography/src/coordinates/reprojection.ts",
	"packages/geography/src/geometryPointContainment.ts",
	"packages/geography/src/geometryPositions.ts",
	"packages/geography/src/geometryTypes.ts",
	"packages/geography/src/geometryProvenance.ts",
	"packages/shapefile/src/shapefile.ts",
	"packages/shapefile/src/dbf.ts",
];

export const buildMapResources = async (
	root: string,
	log: (line: string) => void = () => {},
	workerUrl?: URL,
) => {
	const out = artifactDirectory(root);
	if (!existsSync(out))
		throw new Error(
			"Create the API public directory before building map resources.",
		);
	const registry = readJsonSync(
		buildArtifactPath(root, "boundary-releases.json"),
	) as { releases: BoundaryReleaseSummary[] };
	const inventory = readJsonSync(join(out, "area-inventory.json")) as {
		releases: Array<{
			geography: string;
			id: string;
			status: string;
			artifact: string;
			recordCount?: number;
		}>;
	};
	const geometrySources = readGeometrySourceLookup(root);
	// The parent only uses this cache for provenance. Each worker has its own
	// one-release cache for geometry and compilation.
	const cache = new AreaGeometryCache(
		root,
		geometrySources,
		1,
		undefined,
		undefined,
		roundKeepingValidity,
	);
	const assets = join(root, "data/build");
	const directory = join(assets, "map-resources");
	mkdirSync(directory, { recursive: true });
	for (const name of readdirSync(directory))
		if (name.startsWith(".staging-"))
			rmSync(join(directory, name), { recursive: true, force: true });

	const compiler = sha256(
		COMPILER_SOURCES.map((path) =>
			readFileSync(join(root, path), "utf8"),
		).join("\0"),
	);
	// Each compiled release's key and descriptor, saved as soon as it is
	// written, so a build stopped part way resumes from the last release it
	// finished rather than from nothing.
	const statePath = join(directory, "build-state.json");
	// A release that cannot be tiled is kept too, with the downloads it was
	// still given, so it is not tried again until its inputs change.
	const previous: Record<
		string,
		| { key: string; descriptor: MapResourceDescriptor }
		| { key: string; unavailable: Unavailable }
	> = existsSync(statePath) ? readJsonSync(statePath) : {};
	const state = { ...previous };
	const saveState = () => {
		const temporary = join(directory, ".build-state.tmp");
		writeFileSync(temporary, JSON.stringify(state) + "\n");
		renameSync(temporary, statePath);
	};
	const manifestPath = join(out, "map-resources.json");

	const resources: MapResourceDescriptor[] = [];
	const unavailable: Unavailable[] = [];
	const compiledIds = new Set<string>();
	const jobs: Job[] = [];
	const ordered: Array<{
		id: string;
		key: string;
		result?: Result;
		job?: number;
	}> = [];
	const staging = mkdtempSync(join(directory, ".staging-"));
	const oldState = existsSync(statePath)
		? readFileSync(statePath)
		: undefined;
	const backups: Array<{ path: string; backup?: string }> = [];
	try {
		for (const identity of inventory.releases) {
			if (identity.status !== "available") continue;
			const { geography, id: boundaryRelease } = identity;
			const release = registry.releases.find(
				(candidate) =>
					candidate.geography === geography &&
					candidate.id === boundaryRelease,
			);
			if (!release)
				throw new Error(
					`No boundary release ${geography}/${boundaryRelease} to compile as a map resource.`,
				);
			const areas = readJsonSync(join(out, identity.artifact)) as {
				areas: Array<{ code: string; name: string }>;
			};
			const names = new Map(
				areas.areas.map((area) => [area.code, area.name]),
			);
			const id = releaseKey(geography, boundaryRelease);
			const key = sha256(
				JSON.stringify({
					compiler,
					geometry: cache.provenance(geography, boundaryRelease)
						.inputHash,
					names: [...names].sort(([a], [b]) => a.localeCompare(b)),
					release,
				}),
			);
			const kept = previous[id];
			// A full-tier download has no file: it is built from the geometry
			// store when asked for.
			const stored = (entry: { artifact?: string }) =>
				!entry.artifact || existsSync(join(assets, entry.artifact));
			if (
				kept?.key === key &&
				"descriptor" in kept &&
				[kept.descriptor.tiles, ...kept.descriptor.features].every(
					stored,
				)
			) {
				ordered.push({
					id,
					key,
					result: { descriptor: kept.descriptor },
				});
				continue;
			}
			if (
				kept?.key === key &&
				"unavailable" in kept &&
				(kept.unavailable.features ?? []).every(stored)
			) {
				ordered.push({
					id,
					key,
					result: { unavailable: kept.unavailable },
				});
				continue;
			}

			const artifact = `map-resources/${geography}-${boundaryRelease}.pmtiles`;
			const job = jobs.length;
			jobs.push({
				root,
				release,
				names: [...names],
				artifact,
				path: join(staging, `${job}.pmtiles`),
				large: (identity.recordCount ?? 0) >= 100000,
			});
			ordered.push({ id, key, job });
		}
		const results: Array<Result | undefined> = new Array(jobs.length);
		let cursor = 0;
		const publishReady = () => {
			while (cursor < ordered.length) {
				const item = ordered[cursor]!;
				const result = item.result ?? results[item.job!];
				if (!result) break;
				compiledIds.add(item.id);
				if ("descriptor" in result) {
					const descriptor = result.descriptor;
					if (item.job !== undefined) {
						const target = join(assets, descriptor.tiles.artifact);
						const backup = existsSync(target)
							? join(staging, `backup-${item.job}`)
							: undefined;
						if (backup) copyFileSync(target, backup);
						backups.push({ path: target, backup });
						renameSync(jobs[item.job]!.path, target);
						state[item.id] = { key: item.key, descriptor };
						saveState();
						log(
							`${descriptor.id}: ${formatCount(descriptor.areaCount)} areas, ${formatCount(descriptor.tiles.tileCount)} tiles, ${formatBytes(descriptor.tiles.bytes)}`,
						);
					}
					resources.push(descriptor);
				} else {
					unavailable.push(result.unavailable);
					if (item.job !== undefined) {
						state[item.id] = {
							key: item.key,
							unavailable: result.unavailable,
						};
						saveState();
						log(
							`${item.id}: not tiled, ${result.unavailable.reason}`,
						);
					}
				}
				cursor++;
			}
		};
		publishReady();
		await runMapResourceJobs(
			jobs,
			mapResourceConcurrency(),
			workerUrl,
			(index, result) => {
				results[index] = result;
				publishReady();
			},
			mapResourceMemoryBudget(),
		);
	} catch (error) {
		for (const { path, backup } of backups.reverse()) {
			if (backup) renameSync(backup, path);
			else rmSync(path, { force: true });
		}
		rmSync(join(directory, ".build-state.tmp"), { force: true });
		if (oldState) writeFileSync(statePath, oldState);
		else rmSync(statePath, { force: true });
		throw error;
	} finally {
		rmSync(staging, { recursive: true, force: true });
	}

	// Files left by a release that is no longer compiled, or by an artifact
	// name that has changed, would otherwise be carried into every deployment.
	const current = new Set([
		...resources.flatMap((resource) => [
			resource.tiles.artifact,
			...resource.features.map((entry) => entry.artifact),
		]),
		...unavailable.flatMap((entry) =>
			(entry.features ?? []).map((feature) => feature.artifact),
		),
	]) as Set<string | undefined>;
	for (const name of readdirSync(directory))
		if (
			name !== "build-state.json" &&
			!current.has(`map-resources/${name}`)
		)
			rmSync(join(directory, name));
	for (const id of Object.keys(state))
		if (!compiledIds.has(id)) delete state[id];
	saveState();

	const withoutHash = { schemaVersion: 1 as const, resources, unavailable };
	const manifest = {
		...withoutHash,
		contentHash: sha256(JSON.stringify(withoutHash)),
	};
	writeFileSync(manifestPath, JSON.stringify(manifest, null, "\t") + "\n");
	rmSync(join(out, "map-resources"), { recursive: true, force: true });
	return { path: manifestPath, resources, unavailable };
};
